export const KNOWN_OPCODES = new Set(CORE);

// Shadow/reporter blocks that appear in real sb3s but are not executable
// primitives (menu/shadow editors from scratch-blocks). `note` is the music
// note picker shadow; the math_* / colour_picker / text / matrix entries are
// the inline literal shadows scratch-vm itself generates on deserialize.
const EXTRA_KNOWN = new Set([
    'note',
    'math_number', 'math_positive_number', 'math_whole_number',
    'math_integer', 'math_angle', 'colour_picker', 'text', 'matrix',
    'music_menu_DRUM', 'music_menu_INSTRUMENT', 'music_menu_NOTE',
    'tw_getLastKeyPressed', 'tw_getButtonIsDown',
]);

// Menu opcodes are editor shadow blocks, not VM primitives: anything
// containing "menu" (any case: _menu, _MENU, ...menu suffixes like
// sensing_touchingobjectmenu) is a valid menu.
const MENU_RE = /menu/i;

/** True when `check` should accept the opcode without an unknown-opcode warning. */
export function isKnownOpcode(opcode) {
    return KNOWN_OPCODES.has(opcode) || EXTRA_KNOWN.has(opcode) || MENU_RE.test(opcode);
}
